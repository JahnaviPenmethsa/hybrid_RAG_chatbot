"""
postprocessing.py
-----------------
Takes raw LLM output and wraps it into a structured, safe, citable response.

Output format:
{
    "symptoms_identified": [...],
    "guidance": "...",
    "emergency_alert": true/false,
    "emergency_message": "...",
    "citations": [...],
    "disclaimer": "..."
}
"""

from typing import List, Dict, Any
from app.config import EMERGENCY_KEYWORDS, DISCLAIMER


def detect_emergency(text: str, extracted_symptoms: List[str]) -> bool:
    """Return True if any emergency keyword appears in the raw text or extracted symptoms."""
    combined = text.lower() + " " + " ".join(extracted_symptoms).lower()
    return any(kw in combined for kw in EMERGENCY_KEYWORDS)


def build_citations(docs: List[Dict]) -> List[Dict]:
    """Build citation entries from retrieved documents."""
    citations = []
    for i, doc in enumerate(docs, 1):
        citations.append({
            "ref": i,
            "source": doc.get("source", "Unknown"),
            "relevance_score": round(doc.get("score", 0.0), 4),
            "excerpt": doc.get("text", "")[:200] + "..."
        })
    return citations


def postprocess_response(
    raw_llm_output: str,
    docs: List[Dict],
    extracted_symptoms: List[str]
) -> Dict[str, Any]:
    """
    Assemble the final structured response dict.

    Args:
        raw_llm_output: Text generated by the LLM.
        docs: Retrieved knowledge base chunks.
        extracted_symptoms: Canonical symptom keys matched during extraction.

    Returns:
        Structured dict ready for JSON serialization.
    """
    is_emergency = detect_emergency(raw_llm_output, extracted_symptoms)

    emergency_message = (
        "🚨 EMERGENCY ALERT: Your symptoms may indicate a serious or life-threatening condition. "
        "Please call emergency services (112 / 102 in India) or go to the nearest emergency room immediately."
        if is_emergency else ""
    )

    # Friendly display names for symptoms
    symptom_display = [s.replace("_", " ").title() for s in extracted_symptoms]

    citations = build_citations(docs)

    return {
        "symptoms_identified": symptom_display,
        "emergency_alert": is_emergency,
        "emergency_message": emergency_message,
        "guidance": raw_llm_output if raw_llm_output else (
            "Unable to generate guidance. Please consult a healthcare provider."
        ),
        "citations": citations,
        "disclaimer": DISCLAIMER,
    }


